// Rcon[i] used at round i (1-based); Rcon[0] is unused.
const uint8_t kRcon[11] = {
    0x8d, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
};

void check(cudaError_t err, const char* what) {
    if (err == cudaSuccess) return;
    std::ostringstream os;
    os << what << ": " << cudaGetErrorString(err);
    throw std::runtime_error(os.str());
}

// One thread encrypts one 16-byte block under its own 176-byte round key.
__global__ void aes_ecb_kernel(const uint8_t* round_keys, const uint8_t* in,
                               uint8_t* out, int count) {
    int idx = blockIdx.x * blockDim.x + threadIdx.x;
    if (idx >= count) return;
    uint8_t s[16];
    #pragma unroll
    for (int k = 0; k < 16; ++k) s[k] = in[idx * 16 + k];
    aesdev::encrypt_block(&round_keys[idx * 176], s);
    #pragma unroll
    for (int k = 0; k < 16; ++k) out[idx * 16 + k] = s[k];
}

