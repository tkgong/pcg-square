void aes128_expand_key_host(const uint8_t key[16], uint8_t round_keys[176]) {
    // First round key is the key itself.
    for (int i = 0; i < 16; ++i) round_keys[i] = key[i];

    // Each subsequent 4-byte word.
    for (int i = 4; i < 44; ++i) {
        uint8_t t[4];
        int k = (i - 1) * 4;
        t[0] = round_keys[k + 0];
        t[1] = round_keys[k + 1];
        t[2] = round_keys[k + 2];
        t[3] = round_keys[k + 3];
        if (i % 4 == 0) {
            // RotWord.
            uint8_t tmp = t[0]; t[0] = t[1]; t[1] = t[2]; t[2] = t[3]; t[3] = tmp;
            // SubWord.
            t[0] = kSboxHost[t[0]];
            t[1] = kSboxHost[t[1]];
            t[2] = kSboxHost[t[2]];
            t[3] = kSboxHost[t[3]];
            t[0] ^= kRcon[i / 4];
        }
        int j = i * 4;
        int p = (i - 4) * 4;
        round_keys[j + 0] = round_keys[p + 0] ^ t[0];
        round_keys[j + 1] = round_keys[p + 1] ^ t[1];
        round_keys[j + 2] = round_keys[p + 2] ^ t[2];
        round_keys[j + 3] = round_keys[p + 3] ^ t[3];
    }
}

void aes128_ecb_encrypt_gpu(const uint8_t* keys, const uint8_t* in,
                            uint8_t* out, int count) {
    if (count <= 0) return;

    std::vector<uint8_t> rks(static_cast<size_t>(count) * 176);
    for (int i = 0; i < count; ++i)
        aes128_expand_key_host(&keys[i * 16], &rks[i * 176]);

    uint8_t* d_rk = nullptr;
    uint8_t* d_in = nullptr;
    uint8_t* d_out = nullptr;
    const size_t blk_bytes = static_cast<size_t>(count) * 16;
    check(cudaMalloc(&d_rk, rks.size()), "cudaMalloc d_rk");
    check(cudaMalloc(&d_in, blk_bytes), "cudaMalloc d_in");
    check(cudaMalloc(&d_out, blk_bytes), "cudaMalloc d_out");
    check(cudaMemcpy(d_rk, rks.data(), rks.size(), cudaMemcpyHostToDevice), "H2D rk");
    check(cudaMemcpy(d_in, in, blk_bytes, cudaMemcpyHostToDevice), "H2D in");

    const int block = 128;
    const int grid = (count + block - 1) / block;
    aes_ecb_kernel<<<grid, block>>>(d_rk, d_in, d_out, count);
    check(cudaGetLastError(), "launch aes_ecb_kernel");
    check(cudaDeviceSynchronize(), "sync aes_ecb_kernel");

    check(cudaMemcpy(out, d_out, blk_bytes, cudaMemcpyDeviceToHost), "D2H out");
    cudaFree(d_rk);
    cudaFree(d_in);
    cudaFree(d_out);
}

